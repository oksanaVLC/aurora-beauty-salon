export const ui: Record<Lang, Dict> = { es, en, ru };
export type UIKey = keyof Dict;

export function useTranslations(lang: Lang) {
  return (key: UIKey, vars: Record<string, string | number> = {}) =>
    Object.entries(vars).reduce((s, [k, v]) => s.replace(`{${k}}`, String(v)), ui[lang][key] ?? ui[defaultLang][key]);
}

/** Ruta con prefijo de idioma: ('en', '/cita') → '/en/cita'; ('es', '/cita') → '/cita'. */
export function localePath(lang: Lang, path = '/'): string {
  const clean = path.startsWith('/') ? path : '/' + path;
  return lang === defaultLang ? clean : `/${lang}${clean === '/' ? '/' : clean}`;
}
